#!/usr/bin/env bash
# device:build — prebuild + `gradlew :app:assembleDebug`, fully detached.
#
#   npm run device:build [-- --clean] [-- --force]
#
# Returns at once; the build keeps going in its own session (it survives the
# Bash tool's 10-minute cap). Follow it with `npm run device:wait`.
#   --clean   prebuild --clean (regenerate android/). Automatic when the tree's
#             Expo SDK differs from the one android/ was last generated for.
#   --force   start even if the emulator is running (Gradle + emulator can
#             exhaust RAM on this host).
# Log: mobile/.device/build.log   Status: mobile/.device/build.status
# Gradle flags: $TRACKNOTES_GRADLE_ARGS (default x86_64 only, 3 workers).
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

CLEAN=0; FORCE=0
for arg in "$@"; do
  case "$arg" in
    --clean) CLEAN=1 ;;
    --force) FORCE=1 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) die "Unknown option: $arg (try --help)" ;;
  esac
done

STATUS="$STATE_DIR/build.status"
LOG="$STATE_DIR/build.log"

if [ -f "$STATUS" ]; then
  prev_state="$(grep '^state=' "$STATUS" | cut -d= -f2)"
  prev_pid="$(grep '^pid=' "$STATUS" | cut -d= -f2)"
  if [ "$prev_state" = running ] && pid_alive "$prev_pid"; then
    ok "A build is already running (pid $prev_pid) — not starting another."
    info "Wait for it: npm run device:wait    Log: $LOG"
    exit 0
  fi
fi

[ -d "$MOBILE_DIR/node_modules/expo" ] ||
  die "No node_modules in $MOBILE_DIR. Run \`npm ci --legacy-peer-deps\` in this checkout's mobile/ (never symlink another checkout's)."
command -v java >/dev/null || die "java not found; Gradle needs a JDK (17+) on PATH or JAVA_HOME."
[ -d "$ANDROID_SDK" ] || die "Android SDK not found at $ANDROID_SDK; export ANDROID_HOME."
case "$MOBILE_DIR" in
  /tmp/*) die "This checkout is under /tmp (RAM-backed tmpfs); a ~6 GB Gradle build exhausts it. Build from a checkout on disk." ;;
esac

if [ -n "$(online_devices | grep '^emulator-' || true)" ]; then
  if [ "$FORCE" = 1 ]; then
    warn "The emulator is running; building anyway (--force). Expect swapping."
  else
    die "The emulator is running. Gradle and the emulator together can exhaust this host's RAM.
Close it first (npm run device:stop -- --emulator), or pass --force."
  fi
fi

SDK="$(tree_sdk_major)"
if [ "$CLEAN" = 0 ] && [ -d "$MOBILE_DIR/android" ]; then
  last_sdk="$(cat "$STATE_DIR/prebuild-sdk" 2>/dev/null || true)"
  if [ "$last_sdk" != "$SDK" ]; then
    info "android/ was not generated by device:build for Expo SDK $SDK (recorded: ${last_sdk:-none}) — using prebuild --clean."
    CLEAN=1
  fi
fi

LABEL="$(git_label)"
{
  printf 'state=running\nexit_code=\npid=\nstarted=%s\nfinished=\ngit=%s\nsdk=%s\n' "$(date -Is)" "$LABEL" "$SDK"
} >"$STATUS"
pid="$(detach "$LOG" bash "$DEVICE_SCRIPTS_DIR/build-runner.sh" "$STATUS" "$CLEAN" "$LABEL" "$SDK")"
sed -i "s/^pid=$/pid=$pid/" "$STATUS" # unless the runner already wrote its own

ok "Build started (pid $pid, Expo SDK $SDK, git $LABEL$([ "$CLEAN" = 1 ] && echo ', prebuild --clean'))."
info "A first build takes ~12-15 min. Poll with: npm run device:wait   (blocks up to 9 min per call)"
info "Log: $LOG"
